//==============================================================================
//! 비주얼 컴포넌트. (원본 experimental/visual/visual.js 의 Visual)
//! - 원본은 위치(location) 하나만 드는 뼈대 컴포넌트다. 그리지도 갱신하지도 않는다. 러스트 판도 그대로다.
//==============================================================================
use crate::base::vector2::Vector2;
use crate::core::component::{Component, ComponentBase};

//==============================================================================
/// 비주얼 컴포넌트.
/// - 위치 하나만 든다. 그리지도 갱신하지도 않는다. (is_tick_needed 가 false)
///
/// # 예제
/// 노드에 붙이고 위치 바꾸기
/// ```rust
/// use vanilla::{NodeTree, Vector2, Visual};
///
/// let mut node_tree = NodeTree::new();
/// let node_id = node_tree.create_node("visual");
/// let visual = node_tree.add_component(node_id, Visual::new()).unwrap();
/// assert_eq!(visual.get_location(), Vector2::zero());
/// visual.set_location(Vector2::create(10.0, 20.0));
/// assert_eq!(visual.get_location(), Vector2::create(10.0, 20.0));
/// ```
//==============================================================================
pub struct Visual {
	component_base: ComponentBase,
	location: Vector2,
}

#[crate::reflect]
impl Visual {
	//==============================================================================
	/// 생성. (위치 0)
	///
	/// # 돌려줌
	/// 위치가 (0, 0) 인 새 비주얼.
	//==============================================================================
	pub fn new() -> Visual {
		Visual {
			component_base: ComponentBase::new(),
			location: Vector2::zero(),
		}
	}

	//==============================================================================
	/// 위치 설정.
	///
	/// # 인자
	/// - `location`: 새 위치. (값만 담고 노드 위치는 바꾸지 않는다)
	//==============================================================================
	pub fn set_location(&mut self, location: Vector2) {
		self.location = location;
	}

	//==============================================================================
	/// 위치 반환.
	///
	/// # 돌려줌
	/// 지금 위치.
	//==============================================================================
	pub fn get_location(&self) -> Vector2 {
		self.location
	}
}

impl Default for Visual {
	//==============================================================================
	/// 기본값. (new 와 같다)
	//==============================================================================
	fn default() -> Visual {
		Visual::new()
	}
}

#[crate::reflect]
impl Component for Visual {
	//==============================================================================
	/// 공통 상태 반환.
	//==============================================================================
	fn get_component_base(&self) -> &ComponentBase {
		&self.component_base
	}

	//==============================================================================
	/// 공통 상태 반환. (변경용)
	//==============================================================================
	fn get_component_base_mut(&mut self) -> &mut ComponentBase {
		&mut self.component_base
	}

	//==============================================================================
	/// 컴포넌트 타입 이름. ("Visual")
	//==============================================================================
	fn get_component_type(&self) -> &'static str {
		"Visual"
	}

	//==============================================================================
	/// 갱신할 것이 없다.
	//==============================================================================
	#[reflect(skip)]
	fn is_tick_needed(&self) -> bool {
		false
	}
}
