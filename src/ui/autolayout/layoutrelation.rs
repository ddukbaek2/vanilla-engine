//==============================================================================
// 제약 관계 연산자. (원본 ui/autolayout/layoutrelation.js 의 LayoutRelation)
// - LayoutConstraint 가 식 == 0, <= 0, >= 0 중 어느 쪽인지 가린다.
// - 원본은 문자열 값("==", "<=", ">=")을 담은 객체다. 러스트 판은 열거형이다.
//==============================================================================

//==============================================================================
// 제약 관계 연산자.
//==============================================================================
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum LayoutRelation {
	// 식 == 0
	Equal,
	// 식 <= 0
	LessThanOrEqual,
	// 식 >= 0
	GreaterThanOrEqual,
}
