//==============================================================================
// 수학 보조 함수.
//==============================================================================
use std::cell::Cell;
use web_time::{SystemTime, UNIX_EPOCH};

pub const PI: f32 = std::f32::consts::PI;

thread_local! {
	// 난수 상태. (xorshift64*, 처음 쓸 때 시각으로 씨앗을 정한다)
	static RANDOM_STATE: Cell<u64> = const { Cell::new(0) };
}

//==============================================================================
// 범위 제한.
//==============================================================================
pub fn clamp(value: f32, minimum: f32, maximum: f32) -> f32 {
	if value < minimum {
		return minimum;
	}
	if value > maximum {
		return maximum;
	}
	value
}

//==============================================================================
// 0 ~ 1 범위 제한.
//==============================================================================
pub fn clamp01(value: f32) -> f32 {
	clamp(value, 0.0, 1.0)
}

//==============================================================================
// 도 → 라디안.
//==============================================================================
pub fn degreeToRadian(degree: f32) -> f32 {
	degree * (PI / 180.0)
}

//==============================================================================
// 라디안 → 도.
//==============================================================================
pub fn radianToDegree(radian: f32) -> f32 {
	radian * (180.0 / PI)
}

//==============================================================================
// 선형 보간.
//==============================================================================
pub fn lerp(from: f32, to: f32, time: f32) -> f32 {
	from + (to - from) * time
}

//==============================================================================
// 0 이상 1 미만 난수.
//==============================================================================
pub fn random() -> f32 {
	RANDOM_STATE.with(|randomState| {
		let mut state = randomState.get();
		if state == 0 {
			let nanoseconds = SystemTime::now().duration_since(UNIX_EPOCH).map(|duration| duration.as_nanos() as u64).unwrap_or(0x9E3779B97F4A7C15);
			state = nanoseconds | 1;
		}
		state ^= state >> 12;
		state ^= state << 25;
		state ^= state >> 27;
		randomState.set(state);
		let mixed = state.wrapping_mul(0x2545F4914F6CDD1D);
		((mixed >> 40) as f32) / ((1u64 << 24) as f32)
	})
}

//==============================================================================
// 범위 난수. (minimum 이상 maximum 미만)
//==============================================================================
pub fn randomRange(minimum: f32, maximum: f32) -> f32 {
	let randomValue = random();
	minimum + (maximum - minimum) * randomValue
}

//==============================================================================
// 이징: 바깥으로 감속하는 2차 곡선.
//==============================================================================
pub fn easeOutQuad(time: f32) -> f32 {
	1.0 - (1.0 - time) * (1.0 - time)
}
