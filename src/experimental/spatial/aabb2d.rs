//==============================================================================
//! 축 정렬 경계 상자. (2D, AABB)
//! - 초안: 0.4.0 뒤 기능, API 가 바뀔 수 있다. 원본 src/experimental/spatial/aabb2d.js 와 같은 API, 같은 셈이다.
//! - 가장 작은 꼭짓점(min_x, min_y)과 가장 큰 꼭짓점(max_x, max_y)으로 적는다. 동적 AABB 나무와 2D 물리가 쓴다.
//! - 값은 원본 자바스크립트 수와 같은 f64 다. (두 엔진의 물리 결과를 같게 하려고)
//==============================================================================

//==============================================================================
/// 축 정렬 경계 상자.
///
/// # 예제
/// 두 상자의 겹침과 합친 상자
/// ```rust
/// use vanilla::experimental::spatial::AABB2D;
///
/// let first = AABB2D::create(0.0, 0.0, 10.0, 10.0);
/// let second = AABB2D::create(5.0, 5.0, 20.0, 12.0);
/// assert!(first.overlaps(&second));
/// let combined = AABB2D::combine(&first, &second);
/// assert_eq!(combined, AABB2D::create(0.0, 0.0, 20.0, 12.0));
/// assert_eq!(combined.get_perimeter(), 64.0);
/// ```
//==============================================================================
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct AABB2D {
	/// 가장 작은 x.
	pub min_x: f64,
	/// 가장 작은 y.
	pub min_y: f64,
	/// 가장 큰 x.
	pub max_x: f64,
	/// 가장 큰 y.
	pub max_y: f64,
}

impl AABB2D {
	//==============================================================================
	/// 생성. (모두 0)
	///
	/// # 돌려줌
	/// 네 값이 0 인 상자.
	//==============================================================================
	pub fn new() -> AABB2D {
		AABB2D {
			min_x: 0.0,
			min_y: 0.0,
			max_x: 0.0,
			max_y: 0.0,
		}
	}

	//==============================================================================
	/// 네 값으로 만들기.
	///
	/// # 인자
	/// - `min_x`: 가장 작은 x.
	/// - `min_y`: 가장 작은 y.
	/// - `max_x`: 가장 큰 x.
	/// - `max_y`: 가장 큰 y.
	///
	/// # 돌려줌
	/// 새 상자.
	//==============================================================================
	pub fn create(min_x: f64, min_y: f64, max_x: f64, max_y: f64) -> AABB2D {
		AABB2D {
			min_x,
			min_y,
			max_x,
			max_y,
		}
	}

	//==============================================================================
	/// 두 상자를 감싸는 상자.
	///
	/// # 인자
	/// - `first`: 첫 상자.
	/// - `second`: 둘째 상자.
	///
	/// # 돌려줌
	/// 둘을 모두 담는 가장 작은 상자.
	//==============================================================================
	pub fn combine(first: &AABB2D, second: &AABB2D) -> AABB2D {
		AABB2D::create(first.min_x.min(second.min_x), first.min_y.min(second.min_y), first.max_x.max(second.max_x), first.max_y.max(second.max_y))
	}

	//==============================================================================
	/// 값 설정.
	///
	/// # 인자
	/// - `min_x`: 가장 작은 x.
	/// - `min_y`: 가장 작은 y.
	/// - `max_x`: 가장 큰 x.
	/// - `max_y`: 가장 큰 y.
	//==============================================================================
	pub fn set(&mut self, min_x: f64, min_y: f64, max_x: f64, max_y: f64) {
		self.min_x = min_x;
		self.min_y = min_y;
		self.max_x = max_x;
		self.max_y = max_y;
	}

	//==============================================================================
	/// 둘레 반환. (나무가 표면적 휴리스틱의 값으로 쓴다)
	///
	/// # 돌려줌
	/// 둘레. (2 x (너비 + 높이))
	//==============================================================================
	pub fn get_perimeter(&self) -> f64 {
		let width = self.max_x - self.min_x;
		let height = self.max_y - self.min_y;
		2.0 * (width + height)
	}

	//==============================================================================
	/// 다른 상자와 겹치는지. (경계가 닿기만 해도 겹친다)
	///
	/// # 인자
	/// - `other`: 견줄 상자.
	///
	/// # 돌려줌
	/// 겹치거나 닿으면 true.
	//==============================================================================
	pub fn overlaps(&self, other: &AABB2D) -> bool {
		if other.min_x > self.max_x || other.min_y > self.max_y {
			return false;
		}
		if self.min_x > other.max_x || self.min_y > other.max_y {
			return false;
		}
		true
	}

	//==============================================================================
	/// 다른 상자를 통째로 담는지. (경계 위도 담은 것으로 친다)
	///
	/// # 인자
	/// - `other`: 견줄 상자.
	///
	/// # 돌려줌
	/// other 가 이 상자 안에 있으면 true.
	//==============================================================================
	pub fn contains(&self, other: &AABB2D) -> bool {
		self.min_x <= other.min_x && self.min_y <= other.min_y && other.max_x <= self.max_x && other.max_y <= self.max_y
	}

	//==============================================================================
	/// 점을 담는지. (경계 위도 담은 것으로 친다)
	///
	/// # 인자
	/// - `x`: 점의 x.
	/// - `y`: 점의 y.
	///
	/// # 돌려줌
	/// 점이 상자 안이나 경계 위에 있으면 true.
	//==============================================================================
	pub fn contains_point(&self, x: f64, y: f64) -> bool {
		self.min_x <= x && x <= self.max_x && self.min_y <= y && y <= self.max_y
	}
}
