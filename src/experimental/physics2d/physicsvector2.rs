//==============================================================================
//! 2D 물리의 f64 벡터.
//! - 초안: 0.4.0 뒤 기능, API 가 바뀔 수 있다.
//! - 원본 vanilla.js 의 물리는 자바스크립트 수(f64)로 셈하고 엔진 Vector2 를 주고받는다. 러스트 엔진의 Vector2 는 f32 라,
//!   두 엔진의 물리 결과를 비트까지 같게 하려고 물리 API 는 이 f64 벡터를 주고받는다. (원본의 Vector2 자리)
//! - Vector2(f32)에서 바로 바꿀 수 있고(From), 그리기에는 to_vector2 로 바꿔 쓴다.
//!   원본과 비트까지 같은 결과는 f64 로 만든 값(PhysicsVector2::create(0.1, ..))에서만이다. Vector2::create(0.1, ..) 는 f32 로 반올림된 수라
//!   (0.1 → 0.10000000149011612) 원본의 0.1 과 다른 입력이 된다. 물리 API 의 impl Into<PhysicsVector2> 도 같다.
//==============================================================================
use crate::base::vector2::Vector2;

//==============================================================================
/// 2D 물리의 f64 벡터.
///
/// # 예제
/// 엔진 벡터와 오가기
/// ```rust
/// use vanilla::Vector2;
/// use vanilla::experimental::physics2d::PhysicsVector2;
///
/// let position = PhysicsVector2::create(1.5, -2.0);
/// let engine_position: Vector2 = position.to_vector2();
/// assert_eq!(engine_position, Vector2::create(1.5, -2.0));
/// let back = PhysicsVector2::from(engine_position);
/// assert_eq!(back, position);
/// assert_eq!(PhysicsVector2::create(3.0, 4.0).length(), 5.0);
/// ```
//==============================================================================
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct PhysicsVector2 {
	/// x.
	pub x: f64,
	/// y.
	pub y: f64,
}

impl PhysicsVector2 {
	//==============================================================================
	/// 두 값으로 만들기.
	///
	/// # 인자
	/// - `x`: x.
	/// - `y`: y.
	///
	/// # 돌려줌
	/// 새 벡터.
	//==============================================================================
	pub const fn create(x: f64, y: f64) -> PhysicsVector2 {
		PhysicsVector2 {
			x,
			y,
		}
	}

	//==============================================================================
	/// 영 벡터.
	///
	/// # 돌려줌
	/// (0, 0).
	//==============================================================================
	pub const fn zero() -> PhysicsVector2 {
		PhysicsVector2 {
			x: 0.0,
			y: 0.0,
		}
	}

	//==============================================================================
	/// 길이.
	///
	/// # 돌려줌
	/// 벡터의 길이.
	//==============================================================================
	pub fn length(&self) -> f64 {
		(self.x * self.x + self.y * self.y).sqrt()
	}

	//==============================================================================
	/// 엔진 벡터(f32)로 바꾸기. (그리기, 노드 자리)
	///
	/// # 돌려줌
	/// f32 로 반올림한 Vector2.
	//==============================================================================
	pub fn to_vector2(&self) -> Vector2 {
		Vector2::create(self.x as f32, self.y as f32)
	}
}

impl From<Vector2> for PhysicsVector2 {
	//==============================================================================
	/// 엔진 벡터(f32)에서 바꾸기.
	//==============================================================================
	fn from(vector: Vector2) -> PhysicsVector2 {
		PhysicsVector2::create(vector.x as f64, vector.y as f64)
	}
}
